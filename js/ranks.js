export function getLevelFromLifetimeLC(totalLC) {
    if (!totalLC || totalLC < 0) totalLC = 0;
    return Math.floor(totalLC / LC_PER_LEVEL) + 1;
}

export function getRankFromLevel(level) {
    for (const rank of RANK_LIST) {
        if (level >= rank.minLevel && level <= rank.maxLevel) {
            return rank;
        }
    }
    // Fallback
    return RANK_LIST[RANK_LIST.length - 1];
}

export function getLevelProgressInfo(totalLC) {
    if (!totalLC || totalLC < 0) totalLC = 0;
    const currentLevel = getLevelFromLifetimeLC(totalLC);
    const currentLevelMinimum = (currentLevel - 1) * LC_PER_LEVEL;
    const nextLevelMinimum = currentLevel * LC_PER_LEVEL;
    
    // How much LC we've earned IN THIS LEVEL
    const currentProgress = totalLC - currentLevelMinimum;
    // How much LC is required to pass THIS LEVEL
    const requiredLC = LC_PER_LEVEL;
    
    const percent = Math.min(100, (currentProgress / requiredLC) * 100);
    
    return {
        currentLevel,
        currentProgress,
        requiredLC,
        percent,
        totalLC,
        currentLevelMinimum,
        nextLevelMinimum
    };
}

export function normalizeUserStats(profile) {
    if (!profile) return profile;
    const spendable = Math.max(0, parseInt(profile.lexiCredit) || 0);
    const existingTotal = Math.max(0, parseInt(profile.totalLexiCredit) || 0);
    const levelDerivedTotal = Math.max(0, ((parseInt(profile.level) || 1) - 1) * LC_PER_LEVEL);
    
    // Lifetime credit must be at least spendable balance and at least level threshold
    const trueTotalLC = Math.max(existingTotal, spendable, levelDerivedTotal);
    const trueLevel = Math.max(parseInt(profile.level) || 1, getLevelFromLifetimeLC(trueTotalLC));
    const trueRankObj = getRankFromLevel(trueLevel);

    profile.lexiCredit = spendable;
    profile.totalLexiCredit = trueTotalLC;
    profile.level = trueLevel;
    profile.rank = trueRankObj.title;

    return profile;
}
